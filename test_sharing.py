def test_sql():
    print('the store on Postgres')
    admin = os.environ.get('TEST_ADMIN_DSN', 'postgresql://localhost:5432/postgres?sslmode=disable')
    if 'supabase' in admin or 'pooler' in admin:
        print('  Refusing to run against what looks like a production database.')
        FAILURES.append('admin dsn')
        return
    try:
        import psycopg2
        conn = psycopg2.connect(admin)
        conn.autocommit = True
    except Exception as exc:
        print(f'  No local PostgreSQL available ({exc.__class__.__name__}) — skipping.')
        return
    name = f'shares_test_{os.getpid()}'
    with conn.cursor() as cur:
        cur.execute(f'CREATE DATABASE {name}')
    import importlib
    import src.db
    try:
        dsn = admin.rsplit('/', 1)[0] + f'/{name}?sslmode=disable'
        os.environ['DATABASE_URL'] = dsn
        importlib.reload(src.db)
        share_store._SCHEMA_READY = False
        check('before the table exists: no link, no list', share_store.get('nothing') is None and share_store.list_for(ANN) == [])
        one = share_store.create(ANN, 'session', 'Tuesday', {'name': 'Tuesday', 'n': 1})
        two = share_store.create(ANN, 'program', 'Block', {'name': 'Block'})
        got = share_store.get(one['token'])
        check('a link reads back by its token alone', got['userId'] == ANN and got['kind'] == 'session'
              and got['payload'] == {'name': 'Tuesday', 'n': 1} and got['title'] == 'Tuesday', got)
        check('tokens are long and differ', len(one['token']) >= 20 and one['token'] != two['token'])
        check('listed for the sharer only, newest first', [s['token'] for s in share_store.list_for(ANN)] == [two['token'], one['token']]
              and share_store.list_for(BEN) == [])
        check('only the sharer revokes', not share_store.revoke(BEN, one['token']) and share_store.revoke(ANN, one['token'])
              and share_store.get(one['token']) is None and not share_store.revoke(ANN, one['token'])
              and len(share_store.list_for(ANN)) == 1)
        limit, share_store.MAX_LIVE = share_store.MAX_LIVE, 1
        try:
            try:
                share_store.create(ANN, 'program', 'More', {})
                check('the cap counts live links', False)
            except share_store.TooMany:
                check('the cap counts live links', True)
        finally:
            share_store.MAX_LIVE = limit
        with psycopg2.connect(dsn) as c, c.cursor() as cur:
            cur.execute("SELECT relrowsecurity FROM pg_class WHERE relname = 'shares'")
            check('row security is on (deny-by-default until 015 adds the policy)', cur.fetchone()[0] is True)
            cur.execute("SELECT 1 FROM information_schema.columns WHERE table_name = 'shares' AND column_name = 'user_id'")
            check('account deletion finds it: a public table with a user_id', cur.fetchone() is not None)
            cur.execute('SELECT COUNT(*) FROM shares WHERE revoked_at IS NOT NULL')
            check('a revoked link keeps its row', cur.fetchone()[0] == 1)
    finally:
        src.db.close_conn()
        os.environ['DATABASE_URL'] = ''
        importlib.reload(src.db)
        share_store._SCHEMA_READY = False
        with conn.cursor() as cur:
            cur.execute(f'DROP DATABASE IF EXISTS {name} WITH (FORCE)')
        conn.close()


def test_fixture():
    print('the clients\' fixture')
    if '--write' in sys.argv:
        with open(FIXTURE_PATH, 'w', encoding='utf-8') as fh:
            json.dump(RECORDED, fh, indent=1, ensure_ascii=False, sort_keys=True)
            fh.write('\n')
        print(f'  wrote {FIXTURE_PATH}')
        return
    try:
        with open(FIXTURE_PATH, encoding='utf-8') as fh:
            on_disk = json.load(fh)
    except (OSError, ValueError):
        on_disk = None
    check('frontend/src/mocks/fixtures/shares.json is what the routes answer (run test_sharing.py --write)',
          on_disk == json.loads(json.dumps(RECORDED)))


def main() -> int:
    test_rehome()
    test_recipe()
    test_routes()
    test_fixture()
    test_sql()
    print()
    if FAILURES:
        print(f'{len(FAILURES)} failed: {FAILURES}')
        return 1
