def check(label: str, condition: bool, detail='') -> None:
    if condition:
        print(f"  ok   {label}")
    else:
        print(f"  FAIL {label} {str(detail)[:600]}")
        FAILURES.append(label)


class production:
    """Requests as production sees them: a bearer token whose verified
    subject is `users[token]`; no token is nobody."""

    def __init__(self, users: dict):
        self.users = users

    def __enter__(self):
        self.saved = (auth.SUPABASE_URL, auth._decode_token, os.environ.get('SUPABASE_URL'))
        auth.SUPABASE_URL = 'https://example.invalid'
        os.environ['SUPABASE_URL'] = 'https://example.invalid'

        def decode(token):
            if token not in self.users:
                raise auth.pyjwt.InvalidTokenError('unknown token')
            return {'sub': self.users[token], 'app_metadata': {'roles': []}}
        auth._decode_token = decode
        return self

    def __exit__(self, *exc):
        auth.SUPABASE_URL, auth._decode_token = self.saved[0], self.saved[1]
        os.environ['SUPABASE_URL'] = self.saved[2] or ''


def bearer(token: str) -> dict:
    return {'Authorization': f'Bearer {token}'}


def constraints_for(files: dict) -> dict:
    fw = next(v for k, v in files.items() if k.startswith('frameworks/'))
    exp = yaml.safe_load(fw).get('expectations') or {}
    return {'days_per_week': exp.get('ideal_days_per_week', 4),
            'session_time_minutes': exp.get('ideal_session_minutes', 60), 'training_level': 'intermediate',
            'equipment': [e['id'] for e in api.loader.load_equipment()],
            'injury_flags': [], 'periodization_week': 1, 'fatigue_state': 'normal'}


def test_rehome():
    print('rehome: a package under another athlete\'s prefix')
    pkg, files = package_for(ANN)
    a, b = package_store.owner_prefix(ANN), package_store.owner_prefix(BEN)
    moved = sharing.rehome(files, a, b)
    check('every id and file name moved', a not in json.dumps(moved) and len(moved) == len(files)
          and any(k.startswith(f'frameworks/{b}') for k in moved), sorted(moved))
    check('the same prefix changes nothing', sharing.rehome(files, a, a) == files)
    check('it passes the gate as the receiver\'s own', package_store.check(BEN, moved)['ok'],
          package_store.check(BEN, moved)['problems'])
    check('and for nobody else', not package_store.check(CARL, moved)['ok'])
    check('a private id is told from a shipped one', sharing.private_prefix(pkg) == a
          and sharing.private_prefix('starting_strength') is None and sharing.private_prefix('ux_notprefix') is None)
    check('an id keeps what follows its prefix', sharing.rehome_id(pkg, a, b) == b + pkg[len(a):])


def test_recipe():
    print('recipe: the request that builds a program again')
    one = {'sourceGoalIds': ['alpha'], 'programStartDate': '2026-11-23', 'currentProgram': {
        'goal': {'id': '_phil_alpha', 'name': 'Alpha', 'primary_sources': ['alpha'], 'track': {'id': 't1', 'name': 'Main'}},
        'constraints': {'equipment': ['barbell'], 'training_level': 'elite', 'contract_options': {'swing': 'c'},
                        'module_progression_state': {'m': 3}, 'starting_loads_kg': {'squat': 140}},
        'module_state': {'m': 3},
        'weeks': [{'week_number': 5, 'phase': 'base', 'phase_id': 'p_base', 'phase_name': 'Base', 'track_id': 't1',
                   'schedule': {'Monday': [{}], 'Wednesday': [{}, {}]}},
                  {'week_number': 6, 'phase': 'base', 'phase_id': 'p_base', 'phase_name': 'Base', 'schedule': {'Monday': [{}]}},
                  {'week_number': 7, 'phase': 'build', 'phase_id': 'p_build', 'phase_name': 'Build', 'schedule': {}}]}}
    r = sharing.program_recipe(one)
    check('one track: philosophy, track, start phase, length, options', r == {
        'num_weeks': 3, 'philosophy_id': 'alpha', 'track_id': 't1', 'start_phase': 'p_base',
        'contract_options': {'swing': 'c'}}, r)
    text = json.dumps(r)
    check('nothing of the sharer\'s: no constraints, loads, state or dates',
          not any(w in text for w in ('barbell', 'elite', '140', 'module', '2026')))
    summary = sharing._program_summary(one)
    check('summarised in phases, days and sessions', summary['weeks'] == 3 and summary['daysPerWeek'] == 2
          and summary['sessionsPerWeek'] == 3 and [(p['name'], p['weeks']) for p in summary['phases']]
          == [('Base', 2), ('Build', 1)], summary)

    goal_only = {'currentProgram': {'goal': {'id': '_phil_alpha'}, 'weeks': [{'phase': 'base'}]}}
    check('a program stored without its ids reads its goal',
          sharing.program_recipe(goal_only) == {'num_weeks': 1, 'philosophy_id': 'alpha'})
    blend = {'sourceGoalIds': ['alpha', 'beta'], 'sourceGoalWeights': {'alpha': 0.7, 'beta': 0.3},
             'currentProgram': {'goal': {'id': '_phil_blend'}, 'weeks': [{'track_id': 't1', 'phase_id': 'p'}]}}
    r = sharing.program_recipe(blend)
    check('a blend keeps its weights', r['philosophy_ids'] == ['alpha', 'beta']
          and r['philosophy_weights'] == {'alpha': 0.7, 'beta': 0.3} and r['track_id'] == 't1', r)
    composed = {'sourceGoalIds': ['alpha', 'beta'], 'currentProgram': {
        'composition': {'lanes': [
            {'key': 'alpha/t1', 'philosophy_id': 'alpha', 'track_id': 't1', 'weight': 0.6, 'module_state': {'m': 2}},
            {'key': 'beta/t2', 'philosophy_id': 'beta', 'track_id': 't2', 'weight': 0.4}]},
        'weeks': [{'lanes': [{'lane_key': 'alpha/t1', 'phase_id': 'a_base'}, {'lane_key': 'beta/t2', 'phase_id': 'b_one'}]}]}}
    r = sharing.program_recipe(composed)
    check('a composition is its lanes, each from its own phase, without state', r['lanes'] == [
        {'philosophy_id': 'alpha', 'track_id': 't1', 'weight': 0.6, 'start_phase': 'a_base'},
        {'philosophy_id': 'beta', 'track_id': 't2', 'weight': 0.4, 'start_phase': 'b_one'}]
        and sharing.recipe_packages(r) == ['alpha', 'beta'], r)
    check('a program that names no philosophy has none', sharing.program_recipe({'currentProgram': {'weeks': [{}]}}) is None
          and sharing.program_recipe({}) is None)


