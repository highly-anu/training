#!/usr/bin/env python3
"""Writes the custom `kettlebell` SF Symbol (an SF Symbols 3.0 template SVG).

SF Symbols has no kettlebell. The glyph is drawn on a 100×100 grid (y down):
a wide handle whose window's floor is the top of a round ball with a short
flat base. It is filled, like `dumbbell.fill`; the window winds against the
outline so it is a hole under the non-zero rule.

Only the three required sources (Ultralight-S, Regular-S, Black-S) are
written, with the same outline: a filled glyph does not thin with weight, and
Xcode interpolates the other weights and scales from them.

    python3 ios/tools/make_kettlebell_symbol.py   # rewrites the .symbolset's SVG
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / \
    'TrainingCompanion/Assets.xcassets/kettlebell.symbolset/kettlebell.svg'

# --- the glyph on the 100 grid -------------------------------------------------
CX, CY, R = 50.0, 62.0, 34.0        # the ball
LEG, BASE_Y, WIN = 30.0, 92.0, 21.0  # where the handle meets the ball, the base, the window's floor


def on_ball(dx):
    return CY - math.sqrt(R * R - dx * dx)


def angle(dx):
    return math.degrees(math.atan2(on_ball(dx) - CY, dx))


def arc(a0, a1):
    """Cubic segments along the ball from angle a0 to a1 (degrees, y down)."""
    n = max(1, math.ceil(abs(a1 - a0) / 45))
    out = []
    for i in range(n):
        t0 = math.radians(a0 + (a1 - a0) * i / n)
        t1 = math.radians(a0 + (a1 - a0) * (i + 1) / n)
        k = 4 / 3 * math.tan((t1 - t0) / 4) * R
        p0 = (CX + R * math.cos(t0), CY + R * math.sin(t0))
        p3 = (CX + R * math.cos(t1), CY + R * math.sin(t1))
        c1 = (p0[0] - k * math.sin(t0), p0[1] + k * math.cos(t0))
        c2 = (p3[0] + k * math.sin(t1), p3[1] - k * math.cos(t1))
        out.append(('C', c1, c2, p3))
    return out


def quad(p0, c, p1):
    """A quadratic as the equivalent cubic."""
    return ('C', (p0[0] + 2 / 3 * (c[0] - p0[0]), p0[1] + 2 / 3 * (c[1] - p0[1])),
            (p1[0] + 2 / 3 * (c[0] - p1[0]), p1[1] + 2 / 3 * (c[1] - p1[1])), p1)


def outline():
    base_half = math.sqrt(R * R - (BASE_Y - CY) ** 2)
    a_base = math.degrees(math.atan2(BASE_Y - CY, base_half))
    start = (CX - LEG, on_ball(LEG))
    segs = [('L', (20, 24)), quad((20, 24), (20, 7), (37, 7)), ('L', (63, 7)),
            quad((63, 7), (80, 7), (80, 24)), ('L', (CX + LEG, on_ball(LEG)))]
    segs += arc(angle(LEG), a_base)
    segs.append(('L', (CX - base_half, BASE_Y)))
    segs += arc(180 - a_base, 180 - angle(LEG))
    return start, segs


def window():
    """Drawn the opposite way round to the outline, so it is a hole."""
    start = (CX + WIN, on_ball(WIN))
    segs = [('L', (71, 26)), quad((71, 26), (71, 16), (61, 16)), ('L', (39, 16)),
            quad((39, 16), (29, 16), (29, 26)), ('L', (CX - WIN, on_ball(WIN)))]
    segs += arc(-180 - angle(WIN), angle(WIN))
    return start, segs


# --- placing it in the template --------------------------------------------------
BASELINE_S, CAPLINE_S = 696.0, 625.541
HEIGHT_S = 74.0                      # glyph height in the Small row, ~ the dumbbell's
SCALE = HEIGHT_S / (BASE_Y - 7.0)
COLUMNS = {'Ultralight-S': 559.711, 'Regular-S': 1449.71, 'Black-S': 2369.71}
GLYPH_LEFT, GLYPH_RIGHT = CX - R, CX + R   # the ball is the widest part
SIDEBEARING = 3.0


def path_d(x0, y0):
    def pt(p):
        return f'{x0 + p[0] * SCALE:.3f} {y0 + p[1] * SCALE:.3f}'
    parts = []
    for start, segs in (outline(), window()):
        parts.append(f'M{pt(start)}')
        for s in segs:
            parts.append(f'L{pt(s[1])}' if s[0] == 'L' else f'C{pt(s[1])} {pt(s[2])} {pt(s[3])}')
        parts.append('Z')
    return ''.join(parts)


def svg():
    mid = (BASELINE_S + CAPLINE_S) / 2
    top = mid - (BASE_Y + 7.0) / 2 * SCALE      # centre the glyph on the cap height
    width = (GLYPH_RIGHT - GLYPH_LEFT) * SCALE
    guides, symbols = [], []
    for name, left in COLUMNS.items():
        x0 = left + SIDEBEARING - GLYPH_LEFT * SCALE
        guides.append(f'<line id="left-margin-{name}" style="fill:none;stroke:#00AC8E;stroke-width:0.5;opacity:1.0;" '
                      f'x1="{left:.3f}" x2="{left:.3f}" y1="600.785" y2="720.121"/>')
        right = left + width + 2 * SIDEBEARING
        guides.append(f'<line id="right-margin-{name}" style="fill:none;stroke:#00AC8E;stroke-width:0.5;opacity:1.0;" '
                      f'x1="{right:.3f}" x2="{right:.3f}" y1="600.785" y2="720.121"/>')
        symbols.append(f'<g id="{name}"><path d="{path_d(x0, top)}"/></g>')
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<!--Generated by ios/tools/make_kettlebell_symbol.py — edit the script, not this file.-->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="3300" height="2200">
 <!--glyph: "kettlebell", point size: 100.0, template writer version: "custom"-->
 <g id="Notes">
  <rect height="2200" id="artboard" style="fill:white;opacity:1" width="3300" x="0" y="0"/>
  <text id="template-version" style="stroke:none;fill:black;font-family:sans-serif;font-size:13;" transform="matrix(1 0 0 1 3036 1933)">Template v.3.0</text>
 </g>
 <g id="Guides">
  <line id="Baseline-S" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263.711" x2="3236.84" y1="{BASELINE_S}" y2="{BASELINE_S}"/>
  <line id="Capline-S" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263.711" x2="3236.84" y1="{CAPLINE_S}" y2="{CAPLINE_S}"/>
  <line id="Baseline-M" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263.711" x2="3236.84" y1="1126" y2="1126"/>
  <line id="Capline-M" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263.711" x2="3236.84" y1="1055.54" y2="1055.54"/>
  <line id="Baseline-L" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263.711" x2="3236.84" y1="1556" y2="1556"/>
  <line id="Capline-L" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263.711" x2="3236.84" y1="1485.54" y2="1485.54"/>
  {chr(10).join("  " + g for g in guides).lstrip()}
 </g>
 <g id="Symbols">
  {chr(10).join("  " + s for s in symbols).lstrip()}
 </g>
</svg>
'''


if __name__ == '__main__':
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(svg())
    (OUT.parent / 'Contents.json').write_text(
        '{\n  "info" : {\n    "author" : "xcode",\n    "version" : 1\n  },\n'
        '  "symbols" : [\n    {\n      "filename" : "kettlebell.svg",\n      "idiom" : "universal"\n    }\n  ]\n}\n')
    print(OUT)
