#!/usr/bin/env python3
"""Generate garmin/core/source/gen/Vocab.mc from data/commons/watch_vocabulary.json.

The server (src/watch_spec.py) and the watch read one table: the slot-type
defaults, the template defaults, the palette and the edit steps. The watch uses
them when a payload carries no screen spec (an older server, a session encoded
before ?spec=1) and to check an id it does not know against its own version.

    python3 garmin/tools/gen_vocab.py          # write
    python3 garmin/tools/gen_vocab.py --check  # exit 1 if the file is stale
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'data', 'commons', 'watch_vocabulary.json')
OUT = os.path.join(ROOT, 'garmin', 'core', 'source', 'gen', 'Vocab.mc')


def mc(v) -> str:
    """A Python value as a Monkey C literal."""
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return f'{v}f' if v != int(v) else f'{v:.1f}f'
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return '[' + ', '.join(mc(x) for x in v) + ']'
    if isinstance(v, dict):
        if not v:
            return '{}'
        return '{ ' + ', '.join(f'{mc(k)} => {mc(x)}' for k, x in v.items()) + ' }'
    raise TypeError(type(v))


def render(vocab: dict) -> str:
    d = vocab['defaults']
    lines = [
        '// GENERATED by garmin/tools/gen_vocab.py from data/commons/watch_vocabulary.json.',
        '// Do not edit; change the JSON and rerun the generator.',
        'using Toybox.Lang;',
        '',
        'module Vocab {',
        '',
        f"    const VERSION = {vocab['version']};",
        f"    const FALLBACK_TEMPLATE = {mc(d['fallback_template'])};",
        f"    const WEIGHT_STEP_KG = {mc(float(d['edit']['weight_step_kg']))};",
        '',
        '    // slot_type -> template.',
        '    function templateFor(slotType) {',
        f"        var m = {mc(d['slot_types'])};",
        '        return (slotType != null && m.hasKey(slotType)) ? m[slotType] : FALLBACK_TEMPLATE;',
        '    }',
        '',
        '    // A template\'s default screen, as a fresh dictionary.',
        '    function templateDefaults(t) {',
    ]
    first = True
    for name, tpl in vocab['templates'].items():
        spec = dict(tpl['defaults'], template=name)
        spec.setdefault('gauge', spec.get('a'))
        kw = 'if' if first else '} else if'
        lines.append(f'        {kw} ("{name}".equals(t)) {{')
        lines.append(f'            return {mc(spec)};')
        first = False
    lines += [
        '        }',
        '        return null;',
        '    }',
        '',
        '    // The LAP actions a template allows.',
        '    function actionsFor(t) {',
        f"        var m = {mc({k: v['actions'] for k, v in vocab['templates'].items()})};",
        '        return (t != null && m.hasKey(t)) ? m[t] : [];',
        '    }',
        '',
        '    // A palette token\'s colour, or null.',
        '    function colour(token) {',
        f"        var m = {mc({k: int(v, 16) for k, v in vocab['palette'].items()})};",
        '        return (token != null && m.hasKey(token)) ? m[token] : null;',
        '    }',
        '',
        '    function summaryPages() {',
        f"        return {mc(d['summary']['pages'])};",
        '    }',
        '',
        '    function weightStepByCategory() {',
        f"        return {mc({k: float(v) for k, v in d['edit']['weight_step_by_category'].items()})};",
        '    }',
        '',
        '    function isField(id) {',
        f"        var all = {mc(sorted(vocab['fields']))};",
        '        return id != null && all.indexOf(id) >= 0;',
        '    }',
        '}',
        '',
    ]
    return '\n'.join(lines)


def main() -> int:
    with open(SRC) as f:
        text = render(json.load(f))
    if '--check' in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ''
        if current != text:
            print(f'{os.path.relpath(OUT, ROOT)} is stale: run garmin/tools/gen_vocab.py')
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write(text)
    print(f'wrote {os.path.relpath(OUT, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
