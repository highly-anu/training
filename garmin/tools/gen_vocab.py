#!/usr/bin/env python3
"""Generate the watches' vocabulary from data/commons/watch_vocabulary.json:
garmin/core/source/gen/Vocab.mc for the Garmin and
ios/TrainingCompanion/WatchVocab.swift for the Apple Watch.

The server (src/watch_spec.py) and both watches read one table: the slot-type
defaults, the template defaults, the palette and the edit steps. A watch uses
them when a payload carries no screen spec (an older server, a session encoded
before ?spec=1) and to check an id it does not know against its own version.
The Swift file declares every id as an enum case, and the Apple Watch's
renderer (WatchSpecText) switches over them exhaustively: an id added to the
JSON does not build until the Apple Watch draws it.

    python3 garmin/tools/gen_vocab.py          # write
    python3 garmin/tools/gen_vocab.py --check  # exit 1 if the file is stale
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'data', 'commons', 'watch_vocabulary.json')
OUT = os.path.join(ROOT, 'garmin', 'core', 'source', 'gen', 'Vocab.mc')
OUT_SWIFT = os.path.join(ROOT, 'ios', 'TrainingCompanion', 'WatchVocab.swift')


def mc(v) -> str:
    """A Python value as a Monkey C literal."""
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return f'{v}f' if v != int(v) else f'{v:.1f}f'
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return '[' + ', '.join(mc(x) for x in v) + ']'
    if isinstance(v, dict):
        if not v:
            return '{}'
        return '{ ' + ', '.join(f'{mc(k)} => {mc(x)}' for k, x in v.items()) + ' }'
    raise TypeError(type(v))


def render(vocab: dict) -> str:
    d = vocab['defaults']
    lines = [
        '// GENERATED by garmin/tools/gen_vocab.py from data/commons/watch_vocabulary.json.',
        '// Do not edit; change the JSON and rerun the generator.',
        'using Toybox.Lang;',
        '',
        'module Vocab {',
        '',
        f"    const VERSION = {vocab['version']};",
        f"    const FALLBACK_TEMPLATE = {mc(d['fallback_template'])};",
        f"    const WEIGHT_STEP_KG = {mc(float(d['edit']['weight_step_kg']))};",
        '',
        '    // slot_type -> template.',
        '    function templateFor(slotType) {',
        f"        var m = {mc(d['slot_types'])};",
        '        return (slotType != null && m.hasKey(slotType)) ? m[slotType] : FALLBACK_TEMPLATE;',
        '    }',
        '',
        '    // A template\'s default screen, as a fresh dictionary.',
        '    function templateDefaults(t) {',
    ]
    first = True
    for name, tpl in vocab['templates'].items():
        spec = dict(tpl['defaults'], template=name)
        spec.setdefault('gauge', spec.get('a'))
        kw = 'if' if first else '} else if'
        lines.append(f'        {kw} ("{name}".equals(t)) {{')
        lines.append(f'            return {mc(spec)};')
        first = False
    lines += [
        '        }',
        '        return null;',
        '    }',
        '',
        '    // The LAP actions a template allows.',
        '    function actionsFor(t) {',
        f"        var m = {mc({k: v['actions'] for k, v in vocab['templates'].items()})};",
        '        return (t != null && m.hasKey(t)) ? m[t] : [];',
        '    }',
        '',
        '    // A palette token\'s colour, or null.',
        '    function colour(token) {',
        f"        var m = {mc({k: int(v, 16) for k, v in vocab['palette'].items()})};",
        '        return (token != null && m.hasKey(token)) ? m[token] : null;',
        '    }',
        '',
        '    function summaryPages() {',
        f"        return {mc(d['summary']['pages'])};",
        '    }',
        '',
        '    function weightStepByCategory() {',
        f"        return {mc({k: float(v) for k, v in d['edit']['weight_step_by_category'].items()})};",
        '    }',
        '',
        '    function isField(id) {',
        f"        var all = {mc(sorted(vocab['fields']))};",
        '        return id != null && all.indexOf(id) >= 0;',
        '    }',
        '}',
        '',
    ]
    return '\n'.join(lines)


def case_name(vocab_id: str) -> str:
    """'rpe_or_set' -> 'rpeOrSet'; Swift keywords are escaped."""
    head, *rest = vocab_id.split('_')
    name = head + ''.join(p[:1].upper() + p[1:] for p in rest)
    return f'`{name}`' if name in ('set', 'default', 'case', 'in', 'is', 'as', 'repeat') else name


def swift_enum(name: str, ids, doc: str) -> list[str]:
    out = [f'    /// {doc}', f'    enum {name}: String, CaseIterable, Codable, Sendable {{']
    for i in ids:
        cn = case_name(i)
        bare = cn.strip('`')
        out.append(f'        case {cn}' + (f' = "{i}"' if bare != i else ''))
    out.append('    }')
    return out


def swift_ref(enum: str, v) -> str:
    return 'nil' if v is None else f'.{case_name(v).strip("`")}'


def render_swift(vocab: dict) -> str:
    d = vocab['defaults']
    t_ids = list(vocab['templates'])
    lines = [
        '// GENERATED by garmin/tools/gen_vocab.py from data/commons/watch_vocabulary.json.',
        '// Do not edit; change the JSON and rerun the generator.',
        'import Foundation',
        '',
        '/// The watches\' screen vocabulary (docs/watch.md): the ids a package\'s',
        '/// watch.yaml may name, and each template\'s default screen.',
        'nonisolated enum WatchVocab {',
        f"    static let version = {vocab['version']}",
        '',
    ]
    lines += swift_enum('Template', t_ids, 'The engine mode that runs a step.')
    lines += [''] + swift_enum('Field', list(vocab['fields']), 'What fills one of the data page\'s two fields.')
    lines += [''] + swift_enum('TitlePart', list(vocab['title_parts']), 'A part of the title line.')
    lines += [''] + swift_enum('Line', list(vocab['lines']), 'What the two lines under the rule say.')
    lines += [''] + swift_enum('Action', list(vocab['actions']), 'What LAP (the primary button) does.')
    lines += [''] + swift_enum('Behaviour', list(vocab['behaviours']), 'A package behaviour.')
    lines += [
        '',
        '    struct Defaults: Sendable {',
        '        let title: [TitlePart]',
        '        let a: Field?',
        '        let b: Field?',
        '        let gauge: Field?',
        '        let lines: Line?',
        '        let lap: Action',
        '    }',
        '',
        '    /// Each template\'s default screen.',
        '    static let templateDefaults: [Template: Defaults] = [',
    ]
    for name, tpl in vocab['templates'].items():
        df = tpl['defaults']
        title = ', '.join(swift_ref('TitlePart', x) for x in df.get('title', []))
        gauge = df.get('gauge', df.get('a'))
        lines.append(f"        {swift_ref('Template', name)}: Defaults(title: [{title}], "
                     f"a: {swift_ref('Field', df.get('a'))}, b: {swift_ref('Field', df.get('b'))}, "
                     f"gauge: {swift_ref('Field', gauge)}, lines: {swift_ref('Line', df.get('lines'))}, "
                     f"lap: {swift_ref('Action', df['lap'])}),")
    lines += ['    ]', '', '    /// The LAP actions a template allows.', '    static let actions: [Template: [Action]] = [']
    for name, tpl in vocab['templates'].items():
        acts = ', '.join(swift_ref('Action', a) for a in tpl['actions'])
        lines.append(f"        {swift_ref('Template', name)}: [{acts}],")
    lines += ['    ]', '', '    /// slot_type -> template, for a payload without a screen spec.',
              '    static let slotTypes: [String: Template] = [']
    for slot, t in d['slot_types'].items():
        lines.append(f'        "{slot}": {swift_ref("Template", t)},')
    lines += [
        '    ]',
        f"    static let fallbackTemplate: Template = {swift_ref('Template', d['fallback_template'])}",
        '',
        '    /// The vocabulary\'s field labels ("REPS", "RPE|SET").',
        '    static let fieldLabels: [Field: String] = [',
    ]
    for fid, f in vocab['fields'].items():
        lines.append(f'        {swift_ref("Field", fid)}: "{f["label"]}",')
    lines += [
        '    ]',
        '',
        f"    static let weightStepKg = {float(d['edit']['weight_step_kg'])}",
        '    static let weightStepByCategory: [String: Double] = ['
        + ', '.join(f'"{k}": {float(v)}' for k, v in d['edit']['weight_step_by_category'].items()) + ']',
        '    static let summaryPages: [String] = [' + ', '.join(f'"{p}"' for p in d['summary']['pages']) + ']',
        '    static let palette: [String: UInt32] = ['
        + ', '.join(f'"{k}": {v}' for k, v in vocab['palette'].items()) + ']',
        '}',
        '',
    ]
    return '\n'.join(lines)


def main() -> int:
    with open(SRC) as f:
        vocab = json.load(f)
    outputs = {OUT: render(vocab), OUT_SWIFT: render_swift(vocab)}
    if '--check' in sys.argv:
        stale = [p for p, text in outputs.items()
                 if (open(p).read() if os.path.exists(p) else '') != text]
        for p in stale:
            print(f'{os.path.relpath(p, ROOT)} is stale: run garmin/tools/gen_vocab.py')
        return 1 if stale else 0
    for path, text in outputs.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w') as f:
            f.write(text)
        print(f'wrote {os.path.relpath(path, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
