#!/usr/bin/env python3
"""Generate the package-module registry for the watch.

Reads garmin/packages/<id>/package.json ({"id": ..., "class": ...}) and writes

  garmin/core/source/gen/Registry.mc       Registry.create(id) -> the module, or null
  garmin/TrainingCompanionCIQ/packages.jungle  each module's source/resources paths

A module is only valid for an installed package (data/packages/<id>), its class
must be defined in its sources, and its sources must stay out of the glance and
background images (no (:glance) / (:background)), whose 64 KB they would eat.

    .venv/bin/python garmin/tools/gen_registry.py          # write
    .venv/bin/python garmin/tools/gen_registry.py --check  # exit 1 if stale or invalid
    .venv/bin/python garmin/tools/gen_registry.py --without bjj,crossfit
        # a build without those modules (their slots draw the declarative
        # screens); rerun without --without before committing
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PKG_DIR = os.path.join(ROOT, 'garmin', 'packages')
DATA_PKGS = os.path.join(ROOT, 'data', 'packages')
REGISTRY = os.path.join(ROOT, 'garmin', 'core', 'source', 'gen', 'Registry.mc')
JUNGLE = os.path.join(ROOT, 'garmin', 'TrainingCompanionCIQ', 'packages.jungle')


def modules() -> tuple[list, list]:
    found, errors = [], []
    for manifest in sorted(glob.glob(os.path.join(PKG_DIR, '*', 'package.json'))):
        d = os.path.dirname(manifest)
        name = os.path.basename(d)
        with open(manifest) as f:
            m = json.load(f)
        where = os.path.relpath(manifest, ROOT)
        if m.get('id') != name:
            errors.append(f"{where}: id {m.get('id')!r} must equal the directory")
        if not os.path.isfile(os.path.join(DATA_PKGS, name, 'philosophy.yaml')):
            errors.append(f'{where}: no installed package {name!r} in data/packages')
        cls = m.get('class') or ''
        if not re.fullmatch(r'[A-Z][A-Za-z0-9_]*', cls):
            errors.append(f'{where}: class {cls!r} is not a class name')
        sources = glob.glob(os.path.join(d, 'source', '**', '*.mc'), recursive=True)
        text = ''.join(open(p, encoding='utf-8').read() for p in sources)
        if cls and not re.search(r'\bclass\s+' + re.escape(cls) + r'\s+extends\s+PackageModule\b', text):
            errors.append(f'{where}: no "class {cls} extends PackageModule" in its sources')
        if re.search(r'\(:\s*(glance|background)', text):
            errors.append(f'{where}: module sources must not join the glance or background image')
        found.append({'id': name, 'class': cls,
                      'resources': os.path.isdir(os.path.join(d, 'resources'))})
    return found, errors


def render(mods: list) -> tuple[str, str]:
    reg = [
        '// GENERATED by garmin/tools/gen_registry.py from garmin/packages/*/package.json.',
        '// Do not edit; add or remove a module directory and rerun the generator.',
        '',
        '// Package modules compiled into this build (see PackageModule).',
        'module Registry {',
        '',
        '    // The module for a package id, or null when this build has none.',
        '    function create(id) {',
        '        if (id == null) { return null; }',
    ]
    for m in mods:
        reg.append(f'        if (id.equals("{m["id"]}")) {{ return new {m["class"]}(); }}')
    reg += ['        return null;', '    }', '}', '']
    jungle = [
        '# GENERATED by garmin/tools/gen_registry.py: the package modules (garmin/packages/<id>).',
        '# build.sh passes it after monkey.jungle. Empty when no package ships a module.',
    ]
    for m in mods:
        jungle.append(f'base.sourcePath = $(base.sourcePath);../packages/{m["id"]}/source')
        if m['resources']:
            jungle.append(f'base.resourcePath = $(base.resourcePath);../packages/{m["id"]}/resources')
    return '\n'.join(reg), '\n'.join(jungle) + '\n'


def main() -> int:
    mods, errors = modules()
    if '--without' in sys.argv:
        drop = set(sys.argv[sys.argv.index('--without') + 1].split(','))
        mods = [m for m in mods if m['id'] not in drop]
    for e in errors:
        print(e)
    if errors:
        return 1
    reg, jungle = render(mods)
    if '--check' in sys.argv:
        stale = [p for p, t in ((REGISTRY, reg), (JUNGLE, jungle))
                 if not os.path.exists(p) or open(p).read() != t]
        for p in stale:
            print(f'{os.path.relpath(p, ROOT)} is stale: run garmin/tools/gen_registry.py')
        return 1 if stale else 0
    for p, t in ((REGISTRY, reg), (JUNGLE, jungle)):
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w') as f:
            f.write(t)
        print(f'wrote {os.path.relpath(p, ROOT)} ({len(mods)} module(s))')
    return 0


if __name__ == '__main__':
    sys.exit(main())
