#!/usr/bin/env python3
"""Generate the clients' modality and phase-kind tables from the commons.

Each modality's file (data/commons/modalities/<id>.yaml) and each phase kind
(data/commons/phase_kinds.yaml) carries a `display` block — its label, its one
colour, the web's Tailwind tint and text shade, and for a modality its icon on
the web (lucide), the phone and the Apple Watch (SF Symbols). The web, the
phone, its widgets, the Apple Watch and its widgets each kept their own copy
of these, and they had drifted (the phone said "Movement Skill" where the web
said "Movement / Skill", the watch complication drew system colours). Now a
modality or phase kind added to the commons reaches every client by running
this, with no client edit:

    frontend/src/lib/gen/clientVocab.ts          (lib/modalityColors.ts, modalityIcons.ts, phaseColors.ts)
    ios/TrainingCompanion/ClientVocab.swift      (ModalityStyle, PhaseStyle)
    ios/TrainingWidgets/ClientVocab.swift        (WidgetModalityStyle)
    ios/TrainingCompanionWatch Watch App/ClientVocab.swift   (the watch's ModalityStyle)
    ios/TrainingWatchWidgets/ClientVocab.swift   (the complications)

One Swift file per target folder: each folder is its own target's
(synchronized groups), so a copy in each needs no project edit.

    python3 tools/gen_client_vocab.py          # write
    python3 tools/gen_client_vocab.py --check  # exit 1 if a file is stale
"""
from __future__ import annotations

import glob
import json
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMMONS = os.path.join(ROOT, 'data', 'commons')
TS_OUT = os.path.join(ROOT, 'frontend', 'src', 'lib', 'gen', 'clientVocab.ts')
SWIFT_OUT = [os.path.join(ROOT, 'ios', folder, 'ClientVocab.swift') for folder in (
    'TrainingCompanion', 'TrainingWidgets', 'TrainingCompanionWatch Watch App', 'TrainingWatchWidgets')]
HEADER = ('GENERATED by tools/gen_client_vocab.py from data/commons/modalities/*.yaml and '
          'data/commons/phase_kinds.yaml.', 'Do not edit; change the data and rerun the generator.')


def load() -> tuple[list[tuple[str, dict]], list[tuple[str, dict]]]:
    """(modalities by id, phase kinds in the file's order), each with its display."""
    modalities = []
    for path in sorted(glob.glob(os.path.join(COMMONS, 'modalities', '*.yaml'))):
        with open(path, encoding='utf-8') as fh:
            m = yaml.safe_load(fh)
        if not m.get('display'):
            raise SystemExit(f'{os.path.relpath(path, ROOT)} has no display block')
        modalities.append((m['id'], m['display']))
    modalities.sort(key=lambda x: (x[1].get('order', 999), x[0]))
    with open(os.path.join(COMMONS, 'phase_kinds.yaml'), encoding='utf-8') as fh:
        kinds = yaml.safe_load(fh) or {}
    phases = []
    for kind, body in kinds.items():
        if not (body or {}).get('display'):
            raise SystemExit(f'phase kind {kind} has no display block')
        phases.append((kind, body['display']))
    return modalities, phases


def _classes(d: dict, border: bool) -> dict:
    t = d['tint']
    out = {'bg': f'bg-{t}-500/15', 'text': f"text-{t}-{d['text_shade']} dark:text-{t}-300"}
    if border:
        out['border'] = f'border-{t}-500/40'
    return out


def _ts(value: str) -> str:
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def render_ts(modalities, phases) -> str:
    icons = sorted({d['icon']['web'] for _, d in modalities})
    q = _ts
    lines = [f'// {HEADER[0]}', f'// {HEADER[1]}', '',
             f"import {{ {', '.join(icons)}, type LucideIcon }} from 'lucide-react'", '',
             '/** Every modality the commons define (data/commons/modalities), in their `order`. */',
             'export const MODALITY_IDS = [' + ', '.join(q(i) for i, _ in modalities) + '] as const',
             'export type ModalityId = (typeof MODALITY_IDS)[number]', '',
             '/** Every phase kind (data/commons/phase_kinds.yaml), in its order. */',
             'export const PHASE_KINDS = [' + ', '.join(q(k) for k, _ in phases) + '] as const',
             'export type PhaseKind = (typeof PHASE_KINDS)[number]', '',
             'export interface ModalityDisplay {', '  hex: string', '  bg: string', '  text: string',
             '  border: string', '  label: string', '  icon: LucideIcon', '}', '',
             'export interface PhaseDisplay {', '  hex: string', '  bg: string', '  text: string',
             '  label: string', '}', '',
             'export const MODALITY_DISPLAY: Record<ModalityId, ModalityDisplay> = {']
    for mid, d in modalities:
        c = _classes(d, border=True)
        lines.append(f"  {mid}: {{ hex: {q(d['color'])}, bg: {q(c['bg'])}, text: {q(c['text'])}, "
                     f"border: {q(c['border'])}, label: {q(d['label'])}, icon: {d['icon']['web']} }},")
    lines += ['}', '', 'export const PHASE_DISPLAY: Record<PhaseKind, PhaseDisplay> = {']
    for kind, d in phases:
        c = _classes(d, border=False)
        lines.append(f"  {kind}: {{ hex: {q(d['color'])}, bg: {q(c['bg'])}, text: {q(c['text'])}, "
                     f"label: {q(d['label'])} }},")
    lines += ['}', '']
    return '\n'.join(lines)


def _hex(color: str) -> str:
    return '0x' + color.lstrip('#').lower()


def render_swift(modalities, phases) -> str:
    q = json.dumps
    lines = [f'// {HEADER[0]}', f'// {HEADER[1]}', 'import SwiftUI', '',
             '/// The modality and phase-kind vocabulary every client draws alike: one',
             '/// label, one colour, an icon for the phone and one for the watch.',
             'enum ClientVocab {',
             '    struct Modality {',
             '        let label: String',
             '        let short: String',
             '        let hex: UInt32',
             '        let icon: String',
             '        let watchIcon: String',
             '    }',
             '',
             '    struct Phase {',
             '        let label: String',
             '        let hex: UInt32',
             '    }',
             '',
             '    static let modalities: [String: Modality] = [']
    for mid, d in modalities:
        lines.append(f"        {q(mid)}: Modality(label: {q(d['label'])}, short: {q(d['short'])}, hex: {_hex(d['color'])}, "
                     f"icon: {q(d['icon']['ios'])}, watchIcon: {q(d['icon']['watch'])}),")
    lines += ['    ]', '', '    static let phases: [String: Phase] = [']
    for kind, d in phases:
        lines.append(f"        {q(kind)}: Phase(label: {q(d['label'])}, hex: {_hex(d['color'])}),")
    lines += ['    ]', '',
              '    /// An sRGB colour from 0xRRGGBB.',
              '    static func color(_ hex: UInt32) -> Color {',
              '        Color(red: Double((hex >> 16) & 0xff) / 255,',
              '              green: Double((hex >> 8) & 0xff) / 255,',
              '              blue: Double(hex & 0xff) / 255)',
              '    }',
              '}', '']
    return '\n'.join(lines)


def outputs() -> dict[str, str]:
    modalities, phases = load()
    swift = render_swift(modalities, phases)
    return {TS_OUT: render_ts(modalities, phases), **{p: swift for p in SWIFT_OUT}}


def main() -> int:
    check = '--check' in sys.argv
    stale = []
    for path, text in outputs().items():
        current = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if current == text:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8') as fh:
                fh.write(text)
            print(f'wrote {os.path.relpath(path, ROOT)}')
    if stale:
        print('stale — run python3 tools/gen_client_vocab.py:\n  ' + '\n  '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
